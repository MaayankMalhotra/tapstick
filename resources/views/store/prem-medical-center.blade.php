        // Calculate Clinic Live Status in Indian Standard Time (IST)
        function updateLiveStatus() {
            const statusEl = document.getElementById('liveStatusText');
            if (!statusEl) return;

            const now = new Date();
            // Convert to IST (UTC + 5:30)
            const utc = now.getTime() + (now.getTimezoneOffset() * 60000);
            const istDate = new Date(utc + (3600000 * 5.5));
            const day = istDate.getDay(); // 0 = Sun, 1 = Mon ... 6 = Sat
            const hour = istDate.getHours();
            const min = istDate.getMinutes();
            const timeVal = hour + (min / 60);

            let isOpen = false;
            let closingStr = "";

            if (day >= 1 && day <= 5) { // Mon - Fri: 10:00 AM - 9:00 PM (21.0)
                if (timeVal >= 10.0 && timeVal < 21.0) {
                    isOpen = true;
                    closingStr = "Open Now &bull; Closes at 9:00 PM";
                }
            } else if (day === 6) { // Saturday: 9:00 AM - 10:30 PM (22.5)
                if (timeVal >= 9.0 && timeVal < 22.5) {
                    isOpen = true;
                    closingStr = "Open Now &bull; Closes at 10:30 PM";
                }
            } else if (day === 0) { // Sunday: 10:00 AM - 1:00 PM (13.0)
                if (timeVal >= 10.0 && timeVal < 13.0) {
                    isOpen = true;
                    closingStr = "Open Today &bull; Closes at 1:00 PM";
                }
            }

            if (isOpen) {
                statusEl.innerHTML = closingStr;
            } else {
                statusEl.innerHTML = "Clinic Opens at 10:00 AM &bull; Call 0129-4100392";
            }
        }

