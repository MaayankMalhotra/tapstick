        function closeBookingModal() {
            const modal = document.getElementById('bookingModal');
            if (modal) {
                modal.classList.add('hidden');
                modal.classList.remove('flex');
                document.body.style.overflow = 'auto';
            }
        }

        document.getElementById('bookingModal')?.addEventListener('click', (e) => {
            if (e.target.id === 'bookingModal') closeBookingModal();
        });

        function bookSpecificPackage(packageName, doctorName) {
            const reasonSelect = document.getElementById('modalReason');
            const doctorSelect = document.getElementById('modalDoctor');

            if (reasonSelect) {
                for (let i = 0; i < reasonSelect.options.length; i++) {
                    if (reasonSelect.options[i].value.includes(packageName) || packageName.includes(reasonSelect.options[i].value)) {
                        reasonSelect.selectedIndex = i;
                        break;
                    }
                }
            }

            if (doctorSelect && doctorName) {
                for (let i = 0; i < doctorSelect.options.length; i++) {
                    if (doctorSelect.options[i].text.includes(doctorName) || doctorSelect.options[i].value.includes(doctorName)) {
                        doctorSelect.selectedIndex = i;
                        break;
                    }
                }
            }

            openBookingModal();
        }

        function handleModalSubmit(e) {
            e.preventDefault();
            const doctor = document.getElementById('modalDoctor')?.value || 'Senior Specialist';
            const reason = document.getElementById('modalReason')?.value || 'Package Consultation';
            const name = document.getElementById('modalPatientName')?.value.trim() || 'Patient';
            const phone = document.getElementById('modalPatientPhone')?.value.trim() || '';
            const date = document.getElementById('modalPreferredDate')?.value || 'Earliest';
            const time = document.getElementById('modalPreferredTime')?.value || 'Standard clinic hours';

            const message = `*PREM MEDICAL CENTRE APPOINTMENT*%0A%0A*Selected Package / Reason:* ${encodeURIComponent(reason)}%0A*Doctor:* ${encodeURIComponent(doctor)}%0A*Patient Name:* ${encodeURIComponent(name)}%0A*Phone:* ${encodeURIComponent(phone)}%0A*Date:* ${encodeURIComponent(date)}%0A*Time Slot:* ${encodeURIComponent(time)}%0A%0APlease confirm appointment at Sector 19, Faridabad.`;

            closeBookingModal();
            window.open(`https://wa.me/919999999999?text=${message}`, '_blank');
        }

        function toggleMobileMenu() {
            const menu = document.getElementById('mobileMenu');
            if (menu) menu.classList.toggle('hidden');
        }
        document.getElementById('mobileMenuBtn')?.addEventListener('click', toggleMobileMenu);

        function copyAddress() {
            const address = "Prem Medical Centre, Resi-cum Clinic: H. No. 760, Sector-19, Faridabad - 121002 (Haryana). Phone: 0129-4100392";
            navigator.clipboard.writeText(address).then(() => {
                showToast("Address copied to clipboard!");
            });
        }

        function showToast(msg) {
            const toast = document.getElementById('toast');
            const toastMsg = document.getElementById('toastMessage');
            if (toast && toastMsg) {
                toastMsg.innerText = msg;
                toast.classList.remove('hidden');
                toast.classList.add('flex');
                setTimeout(() => {
                    toast.classList.add('hidden');
                    toast.classList.remove('flex');
                }, 3000);
            }
        }
